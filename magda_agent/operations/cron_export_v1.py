import json
import sqlite3
from dataclasses import dataclass, asdict
from typing import List, Dict, Any, Optional, Union
import logging

logger = logging.getLogger(__name__)


@dataclass
class ScheduledTaskConfig:
    name: str
    cron_expr: str
    last_run: Optional[str] = None
    next_run: Optional[str] = None

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)


class HermesCronExporterV1:
    """
    Exports scheduled cron tasks from HermesCronSchedulerV3 SQLite databases or
    scheduler instances into JSON, crontab, and systemd configurations for multi-platform deployment.
    """

    def __init__(self, db_path_or_conn: Union[str, sqlite3.Connection] = ":memory:"):
        """
        Initializes the exporter.

        Args:
            db_path_or_conn: Path to the SQLite database or an active sqlite3 Connection.
        """
        self.db_path_or_conn = db_path_or_conn

    def _get_connection(self) -> sqlite3.Connection:
        if isinstance(self.db_path_or_conn, sqlite3.Connection):
            return self.db_path_or_conn
        if "?" in self.db_path_or_conn:
            return sqlite3.connect(self.db_path_or_conn, uri=True)
        return sqlite3.connect(self.db_path_or_conn)

    def fetch_tasks(self) -> List[ScheduledTaskConfig]:
        """
        Fetches all scheduled jobs from the SQLite database.

        Returns:
            List of ScheduledTaskConfig objects.
        """
        conn = self._get_connection()
        is_managed_conn = isinstance(self.db_path_or_conn, sqlite3.Connection)
        try:
            cursor = conn.cursor()
            # Ensure jobs table exists
            cursor.execute('''
                CREATE TABLE IF NOT EXISTS jobs (
                    name TEXT PRIMARY KEY,
                    cron_expr TEXT,
                    last_run TIMESTAMP,
                    next_run TIMESTAMP
                )
            ''')
            cursor.execute("SELECT name, cron_expr, last_run, next_run FROM jobs ORDER BY name")
            rows = cursor.fetchall()

            tasks = []
            for row in rows:
                tasks.append(
                    ScheduledTaskConfig(
                        name=row[0],
                        cron_expr=row[1],
                        last_run=row[2],
                        next_run=row[3]
                    )
                )
            return tasks
        finally:
            if not is_managed_conn:
                conn.close()

    def export_jobs_dict(self) -> List[Dict[str, Any]]:
        """
        Exports scheduled tasks as a list of dictionaries.
        """
        tasks = self.fetch_tasks()
        return [task.to_dict() for task in tasks]

    def export_jobs_json(self, indent: int = 2) -> str:
        """
        Exports scheduled tasks formatted as a JSON string.
        """
        jobs = self.export_jobs_dict()
        return json.dumps({"scheduled_tasks": jobs}, indent=indent)

    def export_crontab(
        self,
        command_prefix: str = "python3 -m magda_agent.operations.runner",
        comment_header: bool = True
    ) -> str:
        """
        Exports scheduled tasks as a standard crontab file format string.

        Args:
            command_prefix: Command executable prefix for running each task.
            comment_header: Whether to include header comment.

        Returns:
            Crontab formatted string.
        """
        tasks = self.fetch_tasks()
        lines = []

        if comment_header:
            lines.append("# Hermes Agent Exported Crontab")
            lines.append("# Generated by HermesCronExporterV1")

        for task in tasks:
            lines.append(f"{task.cron_expr} {command_prefix} --task {task.name}")

        return "\n".join(lines) + ("\n" if lines else "")

    def export_systemd_units(
        self,
        exec_start_prefix: str = "/usr/bin/python3 -m magda_agent.operations.runner",
        working_dir: str = "/opt/magda_agent"
    ) -> Dict[str, Dict[str, str]]:
        """
        Exports systemd .service and .timer configs for each task.

        Returns:
            Dict mapping task name to a dict with "service" and "timer" unit content strings.
        """
        tasks = self.fetch_tasks()
        units = {}

        for task in tasks:
            service_unit = (
                f"[Unit]\n"
                f"Description=Hermes Scheduled Task: {task.name}\n\n"
                f"[Service]\n"
                f"Type=oneshot\n"
                f"WorkingDirectory={working_dir}\n"
                f"ExecStart={exec_start_prefix} --task {task.name}\n"
            )

            # Convert cron expression or use OnCalendar spec if needed;
            # Simple conversion or standard OnCalendar string
            timer_unit = (
                f"[Unit]\n"
                f"Description=Hermes Scheduled Task Timer: {task.name}\n\n"
                f"[Timer]\n"
                f"OnCalendar={task.cron_expr}\n"
                f"Persistent=true\n\n"
                f"[Install]\n"
                f"WantedBy=timers.target\n"
            )

            units[task.name] = {
                "service": service_unit,
                "timer": timer_unit
            }

        return units
